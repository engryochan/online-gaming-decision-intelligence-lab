from pathlib import Path


根目录 = Path(__file__).resolve().parents[2]


def 写入文件(相对路径: str, 内容: list[str]) -> None:
    文件路径 = 根目录 / 相对路径
    文件路径.parent.mkdir(parents=True, exist_ok=True)
    文件路径.write_text(
        "\n".join(内容) + "\n",
        encoding="utf-8",
    )
    print(f"已生成：{文件路径.relative_to(根目录)}")


